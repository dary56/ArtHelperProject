    @property
    def position_with_department(self):
        """Должность в связке с кафедрой, например: 'доцент кафедры информационных систем'"""
        if self.position and self.department:
            return f"{self.position} кафедры {self.department}"
        return self.position or (f"кафедра {self.department}" if self.department else "")

    def __str__(self):
        return f"{self.full_name} ({self.get_role_display()})"